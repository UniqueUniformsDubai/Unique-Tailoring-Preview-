CREATE TABLE customers (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL, phone VARCHAR(20) NOT NULL UNIQUE,
 email VARCHAR(254) NOT NULL DEFAULT '', company VARCHAR(160) NOT NULL DEFAULT '',
 area VARCHAR(160) NOT NULL, marketing TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL, updated_at DATETIME NOT NULL,
 INDEX customers_area(area)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE enquiries (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 customer_id BIGINT UNSIGNED NOT NULL, submission_id CHAR(36) NOT NULL UNIQUE,
 service VARCHAR(80) NOT NULL, details TEXT NOT NULL, snapshot_json TEXT NOT NULL,
 source VARCHAR(20) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'New',
 staff_notes TEXT NOT NULL, marketing TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL, updated_at DATETIME NOT NULL,
 FOREIGN KEY(customer_id) REFERENCES customers(id),
 INDEX enquiries_customer(customer_id), INDEX enquiries_status(status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE rate_limits (id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,key_hash CHAR(64) NOT NULL,happened_at BIGINT NOT NULL,INDEX rate_lookup(key_hash,happened_at)) ENGINE=InnoDB;
